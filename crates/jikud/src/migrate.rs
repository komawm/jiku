//! Deterministic `config.toml` → `config.lua` migration.
//!
//! The emitted file is a full `jiku.config{...}` literal built from the resolved
//! [`JikuConfig`], so it is self-contained and reviewable. Before writing, the
//! generator reloads its own output and fails unless it round-trips to exactly
//! the source configuration.

use std::{
    fs,
    path::{Path, PathBuf},
};

use jiku_memory::expand_tilde_path;
use serde_json::Value as JsonValue;

use crate::config::{ConfigError, JikuConfig};

/// Renders `cfg` as a deterministic `config.lua` document.
///
/// # Complexity
///
/// Time and space `O(E)` over the number of configuration entries.
pub fn render_lua_config(cfg: &JikuConfig) -> Result<String, ConfigError> {
    let value = serde_json::to_value(cfg)
        .map_err(|e| ConfigError::Invalid(format!("failed serializing configuration: {e}")))?;

    let mut out = String::new();
    out.push_str("-- Generated by `jikud --migrate-config` from the resolved configuration.\n");
    out.push_str("-- Review before committing; `api_key_env` names are preserved verbatim and\n");
    out.push_str("-- never resolve to raw secrets.\n\n");
    out.push_str("jiku.config");
    render_value(&value, 0, &mut out);
    out.push('\n');
    Ok(out)
}

/// Renders, round-trip-checks, and writes `cfg` to `out`.
///
/// Refuses to overwrite an existing file unless `force` is set.
pub fn migrate_to_path(cfg: &JikuConfig, out: &Path, force: bool) -> Result<PathBuf, ConfigError> {
    let resolved = expand_tilde_path(out);
    if resolved.exists() && !force {
        return Err(ConfigError::Invalid(format!(
            "refusing to overwrite {} without --force",
            resolved.display()
        )));
    }

    let rendered = render_lua_config(cfg)?;
    let round_trip = crate::lua_config::apply_lua_source(
        JikuConfig::default(),
        &rendered,
        "=generated-config.lua",
    )?;
    if &round_trip != cfg {
        return Err(ConfigError::Invalid(
            "generated config.lua does not round-trip to the source configuration".to_string(),
        ));
    }

    if let Some(parent) = resolved.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent).map_err(|source| ConfigError::Read {
            path: parent.to_path_buf(),
            source,
        })?;
    }
    fs::write(&resolved, rendered).map_err(|source| ConfigError::Read {
        path: resolved.clone(),
        source,
    })?;
    Ok(resolved)
}

fn render_value(value: &JsonValue, indent: usize, out: &mut String) {
    match value {
        JsonValue::Null => out.push_str("nil"),
        JsonValue::Bool(true) => out.push_str("true"),
        JsonValue::Bool(false) => out.push_str("false"),
        JsonValue::Number(number) => render_number(number, out),
        JsonValue::String(text) => render_string(text, out),
        JsonValue::Array(items) => render_array(items, indent, out),
        JsonValue::Object(map) => render_object(map, indent, out),
    }
}

fn render_number(number: &serde_json::Number, out: &mut String) {
    let Some(value) = number.as_f64() else {
        out.push_str(&number.to_string());
        return;
    };
    if !number.is_f64() {
        out.push_str(&number.to_string());
        return;
    }
    // `JikuConfig` stores `f32` values; rendering the shortest `f32` form keeps
    // the file readable while still parsing back to the identical bits.
    let short = (value as f32).to_string();
    if short
        .parse::<f64>()
        .is_ok_and(|parsed| (parsed as f32) == (value as f32))
    {
        out.push_str(&short);
    } else {
        out.push_str(&number.to_string());
    }
}

fn render_array(items: &[JsonValue], indent: usize, out: &mut String) {
    if items.is_empty() {
        out.push_str("{}");
        return;
    }
    let mostly_scalar = items
        .iter()
        .all(|item| !matches!(item, JsonValue::Object(_) | JsonValue::Array(_)));
    if mostly_scalar {
        out.push_str("{ ");
        for (index, item) in items.iter().enumerate() {
            if index > 0 {
                out.push_str(", ");
            }
            render_value(item, indent, out);
        }
        out.push_str(" }");
        return;
    }
    out.push_str("{\n");
    for item in items {
        push_indent(indent + 1, out);
        render_value(item, indent + 1, out);
        out.push_str(",\n");
    }
    push_indent(indent, out);
    out.push('}');
}

fn render_object(map: &serde_json::Map<String, JsonValue>, indent: usize, out: &mut String) {
    let entries: Vec<(&String, &JsonValue)> =
        map.iter().filter(|(_, value)| !value.is_null()).collect();
    if entries.is_empty() {
        out.push_str("{}");
        return;
    }
    out.push_str("{\n");
    for (key, value) in entries {
        push_indent(indent + 1, out);
        render_key(key, out);
        out.push_str(" = ");
        render_value(value, indent + 1, out);
        out.push_str(",\n");
    }
    push_indent(indent, out);
    out.push('}');
}

fn render_key(key: &str, out: &mut String) {
    let mut chars = key.chars();
    let bare = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
    if bare {
        out.push_str(key);
    } else {
        out.push('[');
        render_string(key, out);
        out.push(']');
    }
}

fn render_string(text: &str, out: &mut String) {
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

fn push_indent(level: usize, out: &mut String) {
    for _ in 0..level {
        out.push_str("    ");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn round_trip(cfg: &JikuConfig) {
        let rendered = render_lua_config(cfg).expect("render");
        let back = crate::lua_config::apply_lua_source(
            JikuConfig::default(),
            &rendered,
            "=generated-config.lua",
        )
        .expect("generated file must validate");
        assert_eq!(&back, cfg);
    }

    #[test]
    fn default_config_round_trips() {
        round_trip(&JikuConfig::default());
    }

    #[test]
    fn example_toml_round_trips() {
        let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        let cfg = JikuConfig::load_from_path(&manifest_dir.join("../../examples/config.toml"))
            .expect("example toml");
        round_trip(&cfg);
    }

    #[test]
    fn output_is_byte_stable() {
        let cfg = JikuConfig::default();
        let first = render_lua_config(&cfg).unwrap();
        let second = render_lua_config(&cfg).unwrap();
        assert_eq!(first, second);
        assert!(first.contains("jiku.config{"));
        assert!(first.contains("api_key_env"));
    }

    #[test]
    fn overwrite_requires_force() {
        let dir = std::env::temp_dir().join(format!("jiku-migrate-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        let out = dir.join("config.lua");
        fs::write(&out, "-- existing\n").unwrap();

        let cfg = JikuConfig::default();
        let err = migrate_to_path(&cfg, &out, false).expect_err("must refuse overwrite");
        assert!(err.to_string().contains("without --force"));
        assert_eq!(fs::read_to_string(&out).unwrap(), "-- existing\n");

        migrate_to_path(&cfg, &out, true).expect("force overwrite");
        let written = fs::read_to_string(&out).unwrap();
        assert!(written.contains("jiku.config{"));
        let _ = fs::remove_dir_all(&dir);
    }
}
